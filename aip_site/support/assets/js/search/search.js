// Client-side search over the index generated by templates/search.js.j2.
//
// Results are built with DOM APIs: strings are written via textContent /
// createTextNode only, and terms are matched with plain string search.
(function () {
  'use strict';

  const PAGE_SIZE = 9;
  const SNIPPET_WORDS = 25;
  const CONTEXT_START = 90;
  const CONTEXT_BEFORE = 60;
  const MIN_LENGTH = 3;
  // Each term is a linear scan of the whole index, so keep queries bounded.
  // Raw input is first capped at MAX_RAW_LENGTH. After trimming, input beyond
  // MAX_QUERY_LENGTH characters (cut at a word boundary) and terms beyond
  // MAX_TERMS are ignored.
  const MAX_QUERY_LENGTH = 256;
  const MAX_RAW_LENGTH = 4 * MAX_QUERY_LENGTH;
  const MAX_TERMS = 10;
  const STOP_WORDS = new Set([
    'a', 'about', 'an', 'and', 'are', 'as', 'at', 'be', 'by', 'for', 'from',
    'how', 'i', 'in', 'is', 'it', 'of', 'on', 'or', 'that', 'the', 'this',
    'to', 'was', 'what', 'when', 'where', 'which', 'who', 'why', 'will',
    'with',
  ]);

  function countOccurrences(haystack, needle) {
    let n = 0;
    for (let i = haystack.indexOf(needle); i !== -1;
         i = haystack.indexOf(needle, i + needle.length)) {
      n++;
    }
    return n;
  }

  // Returns {terms, excluded, stopped}. All strings are lower-case.
  function parseQuery(raw) {
    let q = raw.trim().toLowerCase();
    if (q.length > MAX_QUERY_LENGTH) {
      const cut = q.lastIndexOf(' ', MAX_QUERY_LENGTH);
      q = q.slice(0, cut > 0 ? cut : MAX_QUERY_LENGTH).trim();
      // Keep a truncated quoted phrase a phrase.
      if (q[0] === '"' || q[0] === "'") q += q[0];
    }
    if (q.length > 1 && /^(["']).*\1$/.test(q)) {
      const phrase = q.slice(1, -1).trim();
      return {terms: phrase ? [phrase] : [], excluded: [], stopped: false};
    }
    const terms = new Set();
    const excluded = new Set();
    let stopped = false;
    for (const word of q.split(/\s+/)) {
      if (!word) continue;
      if (STOP_WORDS.has(word)) {
        stopped = true;
      } else if (word.length > 1 && word[0] === '-') {
        excluded.add(word.slice(1));
      } else {
        terms.add(word);
      }
    }
    return {
      terms: [...terms].slice(0, MAX_TERMS),
      excluded: [...excluded].slice(0, MAX_TERMS),
      stopped,
    };
  }

  // Only link to pages on this site.
  function isSameOrigin(url) {
    const origin = window.location.origin;
    try {
      return new URL(url, origin).origin === origin;
    } catch (e) {
      return false;
    }
  }

  function search(pages, query) {
    const results = [];
    for (const page of pages) {
      if (!isSameOrigin(page.url)) continue;
      const title = page.title.toLowerCase();
      const text = page.text.toLowerCase();
      const url = page.url.toLowerCase();
      if (query.excluded.some((x) => title.includes(x) || text.includes(x))) {
        continue;
      }
      let score = 0;
      for (const term of query.terms) {
        score += 20 * countOccurrences(title, term);
        score += 20 * countOccurrences(text, term);
        if (url.includes(term)) score += 20;
      }
      if (score > 0) results.push({page, score});
    }
    results.sort((a, b) => b.score - a.score);
    return results;
  }

  // Returns a plain-text excerpt of `text`, starting near the first term.
  //
  // Note: offsets found in the lower-cased string are applied to the original.
  // For the rare characters whose lower-case form has a different length
  // (e.g. U+0130) this can shift the excerpt or highlight slightly; output is
  // always plain text, so this is cosmetic only.
  function makeSnippet(text, terms) {
    let start = 0;
    const first = terms.length ? text.toLowerCase().indexOf(terms[0]) : -1;
    if (first > CONTEXT_START) {
      // Start at a word boundary roughly CONTEXT_BEFORE characters before the
      // match, but never after the match itself.
      start = text.indexOf(' ', first - CONTEXT_BEFORE) + 1;
      if (start <= 0 || start > first) start = first - CONTEXT_BEFORE;
    }
    const words = text.slice(start).split(' ');
    let snippet = words.slice(0, SNIPPET_WORDS).join(' ').trim();
    if (start > 0) snippet = '... ' + snippet;
    if (words.length > SNIPPET_WORDS && !snippet.endsWith('.')) {
      snippet += ' ...';
    }
    return snippet;
  }

  // Appends `text` to `parent`, wrapping case-insensitive matches of any term
  // in <span class="tipue_search_content_bold">. Uses text nodes only.
  function appendHighlighted(parent, text, terms) {
    const lower = text.toLowerCase();
    let i = 0;
    while (i < text.length) {
      let best = -1;
      let bestLen = 0;
      for (const term of terms) {
        const j = lower.indexOf(term, i);
        if (j !== -1 && (best === -1 || j < best ||
                         (j === best && term.length > bestLen))) {
          best = j;
          bestLen = term.length;
        }
      }
      if (best === -1) break;
      if (best > i) {
        parent.appendChild(document.createTextNode(text.slice(i, best)));
      }
      const span = document.createElement('span');
      span.className = 'tipue_search_content_bold';
      span.textContent = text.slice(best, best + bestLen);
      parent.appendChild(span);
      i = best + bestLen;
    }
    if (i < text.length) {
      parent.appendChild(document.createTextNode(text.slice(i)));
    }
  }

  function el(tag, {id, className, text} = {}) {
    const e = document.createElement(tag);
    if (id) e.id = id;
    if (className) e.className = className;
    if (text !== undefined) e.textContent = text;
    return e;
  }

  function link(href, text, className) {
    const a = el('a', {className, text});
    a.href = href;
    return a;
  }

  function renderPagination(container, total, start, raw) {
    const pages = Math.ceil(total / PAGE_SIZE);
    if (pages <= 1) return;
    const current = Math.floor(start / PAGE_SIZE);
    const ul = el('ul', {id: 'tipue_search_foot_boxes'});
    const addItem = (label, pageIndex, accessKey) => {
      const li = el('li');
      li.setAttribute('role', 'navigation');
      if (pageIndex === current) {
        li.className = 'current';
        li.textContent = label;
      } else {
        const params = new URLSearchParams({
          q: raw,
          start: String(pageIndex * PAGE_SIZE),
        });
        const a = link('?' + params.toString(), label, 'tipue_search_foot_box');
        if (accessKey) a.accessKey = accessKey;
        li.appendChild(a);
        // The styled box is larger than the link; make all of it clickable.
        li.addEventListener('click', (e) => {
          if (e.target === li) a.click();
        });
      }
      ul.appendChild(li);
    };
    if (current > 0) addItem('Back', current - 1, 'b');
    const first = Math.max(0, Math.min(current - 1, pages - 3));
    for (let p = first; p < Math.min(pages, first + 3); p++) {
      addItem(String(p + 1), p);
    }
    if (current + 1 < pages) addItem('More', current + 1, 'm');
    const foot = el('div', {id: 'tipue_search_foot'});
    foot.appendChild(ul);
    const nav = el('nav');
    nav.appendChild(foot);
    container.appendChild(nav);
  }

  function isSearchable(query) {
    return query.terms.join(' ').length >= MIN_LENGTH;
  }

  function renderWarning(container, query) {
    let text = 'Nothing found.';
    if (!isSearchable(query)) {
      if (query.stopped) {
        text = 'Nothing found. Common words are largely ignored.';
      } else if (query.terms.length || !query.excluded.length) {
        text = `Search should be ${MIN_LENGTH} characters or more.`;
      }
    }
    container.replaceChildren(el('div', {id: 'tipue_search_warning', text}));
  }

  function render(container, results, query, start, raw) {
    container.replaceChildren();
    container.appendChild(el('div', {
      id: 'tipue_search_results_count',
      text: results.length === 1 ?
          '1 result' : `${results.length.toLocaleString('en-US')} results`,
    }));
    for (const {page} of results.slice(start, start + PAGE_SIZE)) {
      const title = el('div', {className: 'tipue_search_content_title'});
      title.appendChild(link(page.url, page.title));
      container.appendChild(title);

      const url = el('div', {className: 'tipue_search_content_url'});
      url.appendChild(link(page.url, page.url));
      container.appendChild(url);

      if (page.text) {
        const text = el('div', {className: 'tipue_search_content_text'});
        appendHighlighted(text, makeSnippet(page.text, query.terms),
                          query.terms);
        container.appendChild(text);
      }
    }
    renderPagination(container, results.length, start, raw);
  }

  function run() {
    const params = new URLSearchParams(window.location.search);
    const raw = (params.get('q') || '').slice(0, MAX_RAW_LENGTH);
    const input = document.getElementById('tipue_search_input');
    const container = document.getElementById('tipue_search_content');
    if (!raw || !container || typeof tipuesearch === 'undefined') return;
    if (input) input.value = raw;
    const query = parseQuery(raw);
    const results = isSearchable(query) ? search(tipuesearch.pages, query) : [];
    if (!results.length) {
      renderWarning(container, query);
      return;
    }
    let start = parseInt(params.get('start'), 10) || 0;
    if (start < 0 || start >= results.length) start = 0;
    start -= start % PAGE_SIZE;
    render(container, results, query, start, raw);
    document.title = `(${results.length}) ${document.title}`;
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', run);
  } else {
    run();
  }
})();
